"""R classes of Tribit's packages for COMPILING our Java sources of their classes (plans/03_epic03_phase1).

The APK has no R classes: R8 wrote the resource ids into Tribit's code as numbers and dropped R. apktool's
res/values/public.xml keeps every id equal to the APK's (apktool.org/blog/apktool-1.0.0), so R generated from it gives
javac the same numbers; javac inlines them, and the R classes never go into the APK. Resources added in native/ after the
decode are not in public.xml - sources reference only the resources that are.

Usage:  python -I tools/gen_r.py <native/res/values/public.xml> <out-dir> <package>...
[TESTED: 2026-10-16 · as work/spike/gen_r.py: 11 423 ids in 19 types; javac errors 17 458 -> 4 661 in the compile spike,
researches/10 §3]
"""
import collections
import pathlib
import re
import sys

public, out_root, packages = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3:]
if not public.exists() or not packages:
    sys.exit("usage: python -I tools/gen_r.py <public.xml> <out-dir> <package>...")
ids = collections.defaultdict(list)
for kind, name, rid in re.findall(r'<public type="(\w+)" name="([^"]+)" id="(0x[0-9a-f]+)"',
                                  public.read_text(encoding="utf-8")):
    ids[kind].append((name.replace(".", "_").replace("$", "_"), rid))
for pkg in packages:
    lines = [f"package {pkg};", "", "/** Generated by tools/gen_r.py from apktool's public.xml - compile time only. */",
             "public final class R {"]
    for kind in sorted(ids):
        lines.append(f"    public static final class {kind} {{")
        lines += [f"        public static final int {n} = {v};" for n, v in ids[kind]]
        lines.append("    }")
    lines.append("}")
    f = out_root / pkg.replace(".", "/") / "R.java"
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"ok  R for {len(packages)} packages: {sum(map(len, ids.values()))} ids in {len(ids)} types")
